"""
build_worker_data.py — Generate the static data the Cloudflare Worker needs,
straight from the Python backend's own sources so both stay in lock-step.

Outputs:
  worker/data/sop_index.json     TF-IDF index fitted by scikit-learn (vocabulary,
                                 idf, stop words, L2-normalised chunk vectors) plus
                                 chunk metadata. The Worker only has to vectorise
                                 the query, so its rankings match sklearn exactly.
  worker/data/eval_cases.json    The 15 golden eval cases from eval_set.csv.
  migrations/0002_demo_seed.sql  Demo traces, feedback and eval results from
                                 seed/demo_seed.py, with timestamps relative to
                                 the moment the migration is applied.

Run from the repo root after changing SOPs, eval cases or demo seed data:
    python scripts/build_worker_data.py
"""

from __future__ import annotations

import json
import sys
import uuid
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))

import retrieval                      # noqa: E402
import eval_runner                    # noqa: E402
from seed import demo_seed            # noqa: E402

OUT_DATA = ROOT / "worker" / "data"
OUT_MIGRATIONS = ROOT / "migrations"


def build_sop_index() -> None:
    retrieval.reset_index()
    index = retrieval._get_index()
    vec = index._vectorizer
    matrix = index._matrix.tocsr()

    vectors = []
    for row in range(matrix.shape[0]):
        start, end = matrix.indptr[row], matrix.indptr[row + 1]
        vectors.append([[int(i), float(v)] for i, v in zip(matrix.indices[start:end], matrix.data[start:end])])

    payload = {
        "params": {
            "lowercase": vec.lowercase,
            "strip_accents": vec.strip_accents,
            "token_pattern": vec.token_pattern,
            "ngram_range": list(vec.ngram_range),
            "sublinear_tf": vec.sublinear_tf,
            "norm": vec.norm,
        },
        "stop_words": sorted(vec.get_stop_words()),
        "vocabulary": {term: int(i) for term, i in vec.vocabulary_.items()},
        "idf": [float(x) for x in vec.idf_],
        "chunks": [c.as_dict() for c in index.chunks],
        "vectors": vectors,
    }
    _write_json(OUT_DATA / "sop_index.json", payload)
    print(f"sop_index.json: {len(index.chunks)} chunks, {len(vec.vocabulary_)} terms")


def build_eval_cases() -> None:
    cases = [
        {
            "case_id": c.case_id,
            "scenario": c.scenario,
            "area": c.area,
            "type": c.type_,
            "severity_hint": c.severity_hint,
            "expected_action": c.expected_action,
            "expected_output": c.expected_output,
        }
        for c in eval_runner.load_eval_cases()
    ]
    _write_json(OUT_DATA / "eval_cases.json", cases)
    print(f"eval_cases.json: {len(cases)} cases")


def _sql(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def _ts_sql(ts: str) -> str:
    """Re-express a demo_seed._ts() timestamp as 'N days ago at HH:<now mm:ss>' in SQL."""
    dt = datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ")
    days_ago = (demo_seed._NOW.date() - dt.date()).days
    return (
        f"strftime('%Y-%m-%dT', 'now', '-{days_ago} days') || '{dt.hour:02d}' "
        f"|| strftime(':%M:%SZ', 'now')"
    )


def build_demo_seed() -> None:
    # Fixed ids so feedback rows can reference their traces.
    ns = uuid.UUID("2b6f0d0e-6a53-4f39-9a5c-5d1f3c7e8a10")
    trace_ids = [str(uuid.uuid5(ns, f"trace-{i}")) for i in range(len(demo_seed._DEMO_TRACES))]

    lines = [
        "-- Demo data from backend/seed/demo_seed.py (generated by scripts/build_worker_data.py).",
        "-- Timestamps are relative to when this migration is applied, like the Python seed",
        "-- which ran on first startup.",
        "",
    ]
    for tid, t in zip(trace_ids, demo_seed._DEMO_TRACES):
        lines.append(
            "INSERT INTO traces (id, timestamp, user_input, retrieved_chunks, prompt_version, "
            "model_output, latency_ms, input_tokens, output_tokens, error) VALUES ("
            f"{_sql(tid)}, {_ts_sql(t['timestamp'])}, {_sql(t['user_input'])}, {_sql(json.dumps([]))}, "
            f"'v1', {_sql(t['model_output'])}, {t['latency_ms']}, {t['input_tokens']}, "
            f"{t['output_tokens']}, NULL);"
        )
    lines.append("")
    feedback_ts = _ts_sql(demo_seed._ts(0))
    for i, (fb, idx) in enumerate(zip(demo_seed._DEMO_FEEDBACK, demo_seed._FEEDBACK_TRACE_INDICES)):
        lines.append(
            "INSERT INTO feedback (id, trace_id, rating, comment, reviewer_correction, created_at) VALUES ("
            f"{_sql(str(uuid.uuid5(ns, f'feedback-{i}')))}, {_sql(trace_ids[idx])}, {fb['rating']}, "
            f"{_sql(fb.get('comment'))}, {_sql(fb.get('reviewer_correction'))}, {feedback_ts});"
        )
    lines.append("")
    run_ts = _ts_sql(demo_seed._EVAL_RUN_TS)
    for tag, rows in (("actual", demo_seed._EVAL_CASES), ("baseline_always_escalate", demo_seed._EVAL_BASELINE_CASES)):
        for case_id, g, c, e, cl, p in rows:
            lines.append(
                "INSERT INTO eval_results (id, case_id, run_id, model_tag, groundedness, classification, "
                "escalation, clarity, overall_pass, notes, created_at) VALUES ("
                f"{_sql(str(uuid.uuid5(ns, f'eval-{tag}-{case_id}')))}, {_sql(case_id)}, "
                f"{_sql(demo_seed._EVAL_RUN_ID)}, {_sql(tag)}, {g}, {c}, {e}, {cl}, {p}, '', {run_ts});"
            )
    (OUT_MIGRATIONS / "0002_demo_seed.sql").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"0002_demo_seed.sql: {len(trace_ids)} traces, {len(demo_seed._DEMO_FEEDBACK)} feedback, "
          f"{len(demo_seed._EVAL_CASES) + len(demo_seed._EVAL_BASELINE_CASES)} eval results")


def _write_json(path: Path, payload) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    OUT_MIGRATIONS.mkdir(exist_ok=True)
    build_sop_index()
    build_eval_cases()
    build_demo_seed()
